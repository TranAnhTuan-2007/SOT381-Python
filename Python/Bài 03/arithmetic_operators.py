# Các phép toán số học cơ bản
a = 3
b = 6
print("a + b =", a + b)    # 9
print("a - b =", a - b)    # -3
print("a * b =", a * b)    # 18
print("a / b =", a / b)    # 0.5
print("a // b =", a // b)  # 0
print("a % b =", a % b)    # 3
print("a ** b =", a ** b)  # 729

# Phép toán với số thực
x = 6.3
y = 3.6
print("x / y =", x / y)    # 1.75
print("x // y =", x // y)  # 1.0 (là float vì có operand là float)