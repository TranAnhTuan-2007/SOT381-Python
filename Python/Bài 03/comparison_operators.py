# So sánh số học
x = 63
y = 36
print("x == y:", x == y)  # False
print("x != y:", x != y)  # True
print("x > y:", x > y)    # True
print("x < y:", x < y)    # False
print("x >= y:", x >= y)  # True
print("x <= y:", x <= y)  # False

# So sánh chuỗi (theo thứ tự từ điển)
str1 = "apple"
str2 = "banana"

print("str1 == str2:", str1 == str2)        # False
print("str1 < str2:", str1 < str2)          # True (vì 'a' < 'b')
print("'abc' < 'abd':", 'abc' < 'abd')      # True